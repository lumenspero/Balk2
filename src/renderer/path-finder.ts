import { forwardRelationships, getIncoming, getOutgoing } from '../graph-queries.js';
import type { ConnectionMap, Relationship, RelationshipType } from '../types.js';

export interface FormattedPath {
  readonly target: string;
  readonly steps: readonly string[];
}

/**
 * Options for graph path finding.
 */
export interface PathFinderOptions {
  /** Maximum number of relationships in one path (default: 4) */
  readonly maxDepth?: number;
  /** Maximum number of paths to generate per target (default: 3) */
  readonly maxPathsPerTarget?: number;
  /** Maximum total number of path sections in markdown output (default: 10) */
  readonly maxTotalPaths?: number;
  /**
   * Shared nodes with more producers and consumers than this are not passed through, so a hub
   * does not join every pipeline in the repository. The path target itself is always traced.
   * (default: 50; pass Infinity to remove the bound)
   */
  readonly maxDegree?: number;
  /** Also trace paths through event channels (default: true) */
  readonly includeEventChannels?: boolean;
  /** Also trace paths through registry keys: caller → key → target (default: true) */
  readonly includeRegistryKeys?: boolean;
}

/** Relationships that put something into a shared node (data file or event channel). */
const PRODUCES: ReadonlySet<RelationshipType> = new Set([
  'generates',
  'writes',
  'emits',
  'dispatches',
]);

/** Relationships that take something out of a shared node. */
const CONSUMES: ReadonlySet<RelationshipType> = new Set(['consumes', 'reads', 'subscribes']);

const PASSIVE: Readonly<Partial<Record<RelationshipType, string>>> = {
  generates: 'generated by',
  writes: 'written by',
  emits: 'emitted by',
  dispatches: 'dispatched by',
  consumes: 'consumed by',
  reads: 'read by',
  subscribes: 'subscribed by',
};

/**
 * Discover key connection paths through the connection graph.
 *
 * Data artifacts and event channels are the shared nodes things connect through. A path runs
 * from a producer into the shared node and out to a consumer, and keeps going when that consumer
 * itself produces into another shared node, so multi-stage pipelines and chains of events read
 * as one path:
 *
 *   scripts/collect.js → generates → data/raw.json ← consumed by ← scripts/build.js
 *
 * Paths are built from forward relationships only, so the result is the same whether or not
 * the map stores reverse links. A shared node with only producers or only consumers yields
 * single-hop paths. Artifacts are traced before event channels.
 */
export function findConnectionPaths(
  map: ConnectionMap,
  options?: PathFinderOptions,
): readonly FormattedPath[] {
  const maxDepth = options?.maxDepth ?? 4;
  const maxPaths = options?.maxPathsPerTarget ?? 3;
  const maxTotal = options?.maxTotalPaths ?? 10;
  const includeChannels = options?.includeEventChannels ?? true;
  const includeRegistries = options?.includeRegistryKeys ?? true;
  const maxDegree = options?.maxDegree ?? 50;

  const producersOf = new Map<string, Relationship[]>();
  const consumersOf = new Map<string, Relationship[]>();
  const producedBy = new Map<string, Relationship[]>();
  const push = (index: Map<string, Relationship[]>, key: string, rel: Relationship): void => {
    index.set(key, [...(index.get(key) ?? []), rel]);
  };

  for (const rel of forwardRelationships(map)) {
    if (PRODUCES.has(rel.type)) {
      push(producersOf, rel.to, rel);
      push(producedBy, rel.from, rel);
    } else if (CONSUMES.has(rel.type)) {
      push(consumersOf, rel.to, rel);
    }
  }

  const degreeOf = (id: string): number =>
    (producersOf.get(id)?.length ?? 0) + (consumersOf.get(id)?.length ?? 0);

  const isSharedNode = (id: string): boolean =>
    map.artifacts[id] !== undefined || (includeChannels && map.eventChannels[id] !== undefined);

  const targets = [
    ...Object.keys(map.artifacts).sort(),
    ...(includeChannels ? Object.keys(map.eventChannels).sort() : []),
    ...(includeRegistries ? Object.keys(map.registryKeys).sort() : []),
  ];

  // A registry key is reached by a lookup (`resolves` or `routesTo`) and reaches what it is
  // registered to (`registers`). A key with only one side produces no path.
  const registryChainsFrom = (keyId: string): string[][] => {
    const chains: string[][] = [];
    for (const lookup of getIncoming(map, keyId, 'resolves', 'routesTo')) {
      for (const registration of getOutgoing(map, keyId, 'registers')) {
        if (chains.length >= maxPaths) return chains;
        chains.push([
          lookup.from,
          forwardLabel(lookup.type),
          keyId,
          forwardLabel('registers'),
          registration.to,
        ]);
      }
    }
    return chains;
  };

  const chainsFrom = (origin: string): string[][] => {
    const producers = producersOf.get(origin) ?? [];
    const consumers = consumersOf.get(origin) ?? [];
    const results: string[][] = [];

    const singleHops = (): void => {
      for (const rel of [...producers, ...consumers]) {
        if (results.length >= maxPaths) return;
        results.push([rel.from, forwardLabel(rel.type), origin]);
      }
    };

    if (producers.length === 0 || consumers.length === 0 || maxDepth < 2) {
      singleHops();
      return results;
    }

    const extend = (
      node: string,
      steps: readonly string[],
      edgeCount: number,
      visited: ReadonlySet<string>,
    ): void => {
      if (results.length >= maxPaths) return;

      let extended = false;
      if (edgeCount + 2 <= maxDepth) {
        for (const out of producedBy.get(node) ?? []) {
          if (visited.has(out.to) || !isSharedNode(out.to) || degreeOf(out.to) > maxDegree) {
            continue;
          }
          for (const next of consumersOf.get(out.to) ?? []) {
            if (visited.has(next.from)) continue;
            extended = true;
            extend(
              next.from,
              [...steps, forwardLabel(out.type), out.to, reverseLabel(next.type), next.from],
              edgeCount + 2,
              new Set([...visited, out.to, next.from]),
            );
          }
        }
      }

      if (!extended && results.length < maxPaths) results.push([...steps]);
    };

    for (const producer of producers) {
      for (const consumer of consumers) {
        if (producer.from === consumer.from) continue;
        extend(
          consumer.from,
          [
            producer.from,
            forwardLabel(producer.type),
            origin,
            reverseLabel(consumer.type),
            consumer.from,
          ],
          2,
          new Set([producer.from, origin, consumer.from]),
        );
      }
    }

    // Every producer is also a consumer (a script that reads back its own output).
    if (results.length === 0) singleHops();
    return results;
  };

  const accepted: FormattedPath[] = [];
  for (const target of targets) {
    if (accepted.length >= maxTotal) break;

    const chains =
      map.registryKeys[target] !== undefined ? registryChainsFrom(target) : chainsFrom(target);
    for (const steps of chains) {
      if (accepted.length >= maxTotal) break;
      // A path that is a stretch of a longer one adds nothing: the same pipeline is already shown.
      if (accepted.some((path) => isStretchOf(steps, path.steps))) continue;
      for (let i = accepted.length - 1; i >= 0; i--) {
        if (isStretchOf(accepted[i]?.steps ?? [], steps)) accepted.splice(i, 1);
      }
      accepted.push({ target, steps });
    }
  }

  return accepted;
}

function forwardLabel(type: RelationshipType): string {
  return `→ ${type} →`;
}

function reverseLabel(type: RelationshipType): string {
  return `← ${PASSIVE[type] ?? type} ←`;
}

/** True when `inner` appears in `outer` as a run of consecutive steps (and `outer` is longer). */
function isStretchOf(inner: readonly string[], outer: readonly string[]): boolean {
  if (inner.length >= outer.length) return false;
  for (let start = 0; start + inner.length <= outer.length; start++) {
    if (inner.every((step, offset) => outer[start + offset] === step)) return true;
  }
  return false;
}
